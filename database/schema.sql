-- Verificar si el usuario autenticado tiene un rol específico
create or replace function public.auth_tiene_rol(p_rol_codigo text)
returns boolean language sql security definer stable as $$
    select exists (
        select 1
        from public.usuarios u
        join public.roles r on r.id = u.rol_id
        where u.id = auth.uid()
          and u.activo = true
          and r.activo = true
          and r.codigo = p_rol_codigo
    );
$$;

-- Verificar si el usuario tiene un permiso específico (por bits CRUD)
create or replace function public.auth_tiene_permiso(p_modulo text, p_accion text)
returns boolean language sql security definer stable as $$
    select case p_accion
        when 'ver'      then bool_or(rp.ver)
        when 'crear'    then bool_or(rp.crear)
        when 'editar'   then bool_or(rp.editar)
        when 'borrar'   then bool_or(rp.borrar)
        when 'exportar' then bool_or(rp.exportar)
        else false
    end
    from public.usuarios u
    join public.roles_permisos rp on rp.rol_id = u.rol_id
    join public.permisos_modulos pm on pm.id = rp.permiso_modulo_id
    where u.id = auth.uid()
      and u.activo = true
      and pm.codigo_modulo = p_modulo
      and pm.activo = true;
$$;

comment on function public.auth_tiene_permiso is
    'Uso: auth_tiene_permiso(''casos'', ''crear'') — '
    'Verifica el bit específico de la matriz CRUD para el usuario autenticado.';

-- Obtener el distrito del usuario autenticado (para filtros RLS)
create or replace function public.auth_distrito_id()
returns smallint language sql security definer stable as $$
    select distrito_id from public.usuarios where id = auth.uid();
$$;

