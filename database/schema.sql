-- 8.4 Auditoría automática por trigger
-- ------------------------------------
create or replace function public.registrar_auditoria()
returns trigger language plpgsql security definer as $$
declare
    v_superadmin_id uuid;
    v_fue_impersonado boolean := false;
begin
    -- Detectar si la sesión actual es una impersonación activa
    select si.superadmin_id into v_superadmin_id
    from public.sesiones_impersonacion si
    where si.usuario_impersonado_id = auth.uid()
      and si.fecha_fin is null
    limit 1;

    if v_superadmin_id is not null then
        v_fue_impersonado := true;
    end if;

    insert into public.bitacora_auditoria
        (usuario_id, fue_impersonado, superadmin_real_id, accion, tabla_afectada, registro_id, valores_anteriores, valores_nuevos)
    values (
        auth.uid(),
        v_fue_impersonado,
        v_superadmin_id,
        TG_OP,
        TG_TABLE_NAME,
        coalesce(new.id, old.id)::text,
        case when TG_OP = 'DELETE' then to_jsonb(old) else null end,
        case when TG_OP <> 'DELETE' then to_jsonb(new) else null end
    );
    return coalesce(new, old);
end;
$$;

