-- BLOQUE 4: NÚCLEO OPERATIVO — CASOS (tabla única con jerarquía)
-- ============================================================================

create table public.casos (
    id                          bigint generated always as identity primary key,
    -- Jerarquía: una tarea de campo puede ser hija de un caso padre (denuncia)
    caso_padre_id               bigint references public.casos(id) on delete set null,
    categoria_id                bigint not null references public.categorias_caso(id),
    distrito_id                 smallint not null references public.distritos(id),
    canal_reporte_id            smallint not null references public.canales_reporte(id),
    departamento_actual_id      bigint not null references public.departamentos(id),

    -- Creación: o usuario institucional o ciudadano (no ambos)
    creado_por_usuario_id       uuid references public.usuarios(id),
    creado_por_ciudadano_id     uuid references public.ciudadanos(id),

    -- Asignación
    usuario_responsable_id      uuid references public.usuarios(id),
    cuadrilla_responsable_id    bigint references public.cuadrillas(id),

    -- Estado: código del estado según el flujo de la categoría (no FK, es libre)
    estado_codigo               text not null default 'recibida',
    prioridad_id                smallint not null references public.prioridades(id),

    -- Datos del caso
    correlativo                 text unique,
    titulo                      text not null,
    descripcion                 text not null check (char_length(descripcion) between 10 and 2000),
    direccion_referencia        text not null check (char_length(direccion_referencia) between 5 and 300),
    ubicacion                   geography(Point, 4326),
    resolucion                  text,           -- Descripción de resolución al cerrar el caso

    -- Fechas de ciclo de vida
    fecha_recibido              timestamptz,
    fecha_asignado              timestamptz,
    fecha_cierre                timestamptz,
    observaciones_internas      text,

    -- Auditoría
    created_at                  timestamptz not null default now(),
    updated_at                  timestamptz not null default now(),
    deleted_at                  timestamptz,

    -- Restricciones
    constraint ck_casos_creador check (
        (creado_por_usuario_id is not null and creado_por_ciudadano_id is null)
        or
        (creado_por_ciudadano_id is not null and creado_por_usuario_id is null)
    ),
    constraint ck_casos_bbox_sssur check (
        ubicacion is null or (
            st_y(ubicacion::geometry) between 13.50 and 13.85
            and st_x(ubicacion::geometry) between -89.40 and -89.05
        )
    )
);

comment on column public.casos.caso_padre_id is
    'Referencia al caso padre. Permite que una tarea de intervención (empleado) '
    'esté vinculada a la denuncia original que la generó.';

comment on column public.casos.estado_codigo is
