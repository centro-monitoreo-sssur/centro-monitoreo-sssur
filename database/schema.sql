-- ------------------------------------
-- 8.2 Sincronizar campos al crear un caso
-- ------------------------------------
create or replace function public.sincronizar_campos_caso()
returns trigger language plpgsql as $$
declare
    v_departamento_id bigint;
    v_prioridad_id    smallint;
    v_estado_inicial  text;
begin
    -- Obtener defaults de la categoría
    select c.departamento_responsable_id, c.prioridad_default_id, c.estado_inicial
    into v_departamento_id, v_prioridad_id, v_estado_inicial
    from public.categorias_caso c
    where c.id = new.categoria_id;

    -- Aplicar defaults si no se proporcionaron
    if new.departamento_actual_id is null then
        new.departamento_actual_id = v_departamento_id;
    end if;
    if new.prioridad_id is null then
        new.prioridad_id = coalesce(v_prioridad_id, 3);
    end if;
    if new.estado_codigo is null or new.estado_codigo = '' then
        new.estado_codigo = coalesce(v_estado_inicial, 'recibida');
    end if;
    if new.correlativo is null then
        new.correlativo = 'CASO-' || extract(year from now())::text
                         || '-' || lpad(new.id::text, 6, '0');
    end if;

    return new;
end;
$$;

create trigger trg_casos_sync_campos
    before insert on public.casos
    for each row execute function public.sincronizar_campos_caso();

-- ------------------------------------
-- 8.3 Derivación actualiza departamento_actual del caso
-- ------------------------------------
create or replace function public.aplicar_derivacion_caso()
returns trigger language plpgsql as $$
begin
    update public.casos
    set departamento_actual_id = new.departamento_destino_id,
        updated_at = now()
    where id = new.caso_id;
    return new;
end;
$$;

